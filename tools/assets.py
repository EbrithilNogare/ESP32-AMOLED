def _lvgl_image():
    sys.path.insert(0, str(TOOLS / "lvgl"))
    try:
        import LVGLImage  # noqa: E402  (tools/lvgl/LVGLImage.py)
    finally:
        sys.path.pop(0)
    return LVGLImage


def color_format(lvi, cf_name: str, what: str):
    try:
        return lvi.ColorFormat[cf_name]
    except KeyError:
        raise AssetError(f"{what}: unknown format {cf_name!r}") from None


def image_to_c(lvi, png_path: Path, cf_name: str, symbol: str, out: Path, dither: bool) -> str:
    cf = color_format(lvi, cf_name, symbol)
    img = lvi.LVGLImage().from_png(str(png_path), cf=cf, rgb565_dither=dither)
    img.to_c_array(str(out), outputname=symbol)
    return BANNER + out.read_text(encoding="utf-8").lstrip("\n")


def build_images(images: list[dict], work: Path, outputs: dict[Path, bytes]) -> list[tuple[str, str]]:
    decls: list[tuple[str, str]] = []
    if not images:
        return decls
    lvi = _lvgl_image()
    for raw in images:
        name = raw["name"]
        src = ASSETS / raw["file"]
        if not src.is_file():
            raise AssetError(f"image {name}: {src} not found")
        cf_name = raw.get("format", "RGB565A8")
        dest = raw.get("dest", "flash")
        dither = bool(raw.get("dither", False))
        symbol = f"img_{name}"
        if dest == "flash":
            out = work / f"{symbol}.c"
            text = image_to_c(lvi, src, cf_name, symbol, out, dither)
            outputs[GEN_REL / "images" / f"{symbol}.c"] = text.encode("utf-8")
            decls.append((symbol, f"{raw['file']}, {cf_name}"))
            log(f"  image  {symbol}")
        elif dest == "fs":
            comp_name = raw.get("compress", "NONE")
            try:
                comp = lvi.CompressMethod[comp_name]
            except KeyError:
                raise AssetError(f"image {name}: unknown compress {comp_name!r} "
                                 f"(one of {[c.name for c in lvi.CompressMethod]})") from None
            cf = color_format(lvi, cf_name, f"image {name}")
            img = lvi.LVGLImage().from_png(str(src), cf=cf, rgb565_dither=dither)
            out = work / f"{name}.bin"
            img.to_bin(str(out), compress=comp)
            outputs[FS_REL / f"{name}.bin"] = out.read_bytes()
            log(f"  image  {name} -> {(FS_REL / f'{name}.bin').as_posix()}")
        else:
            raise AssetError(f"image {name}: dest must be flash or fs")
    return decls


@dataclass
class SpriteResult:
    name: str
    frames: list[str]
    w: int
    h: int
    fps: int
    loop: int
    desc: str


def build_sprites(sprites: list[dict], work: Path, outputs: dict[Path, bytes]) -> list[SpriteResult]:
    results: list[SpriteResult] = []
    if not sprites:
        return results
    lvi = _lvgl_image()
    import png
    for raw in sprites:
        name = raw["name"]
        src = ASSETS / raw["file"]
        if not src.is_file():
            raise AssetError(f"sprite {name}: {src} not found")
        frame = raw["frame"]
        if not isinstance(frame, list) or len(frame) != 2:
            raise AssetError(f"sprite {name}: frame must be [width, height]")
        fw, fh = (int(v) for v in frame)
        count = int(raw["frames"])
        fps = int(raw.get("fps", 10))
        if fw <= 0 or fh <= 0:
            raise AssetError(f"sprite {name}: frame size {fw}x{fh} must be positive")
        if count <= 0 or fps <= 0:
            raise AssetError(f"sprite {name}: frames and fps must be positive")
        loop_name = raw.get("loop", "loop")
        if loop_name not in SPRITE_LOOP_MODES:
            raise AssetError(f"sprite {name}: loop must be one of {list(SPRITE_LOOP_MODES)}")
        if raw.get("dest", "flash") != "flash":
            raise AssetError(f"sprite {name}: only dest = \"flash\" is supported")
        cf_name = raw.get("format", "RGB565A8")
        dither = bool(raw.get("dither", False))

        sw, sh, rows, _info = png.Reader(filename=str(src)).asRGBA8()
        rows = [bytes(r) for r in rows]
        cols, nrows = sw // fw, sh // fh
        if cols * nrows < count:
            raise AssetError(f"sprite {name}: {sw}x{sh} sheet holds {cols * nrows} frames of "
                             f"{fw}x{fh}, manifest says {count}")
        if count > 0xFFFF or fps > 0xFFFF:
            raise AssetError(f"sprite {name}: frames/fps out of range")

        frames = []
        digits = max(2, len(str(count - 1)))
        for i in range(count):
            r, c = divmod(i, cols)
            frame_rows = [row[c * fw * 4:(c + 1) * fw * 4] for row in rows[r * fh:(r + 1) * fh]]
            frame_png = work / f"sprite_{name}_{i:0{digits}d}.png"
            with frame_png.open("wb") as f:
                png.Writer(fw, fh, greyscale=False, alpha=True, bitdepth=8).write(f, frame_rows)
            symbol = f"sprite_{name}_f{i:0{digits}d}"
            text = image_to_c(lvi, frame_png, cf_name, symbol, work / f"{symbol}.c", dither)
            outputs[GEN_REL / "sprites" / f"{symbol}.c"] = text.encode("utf-8")
            frames.append(symbol)

        table = [BANNER, '#include "../assets.h"\n\n',
                 f"const lv_image_dsc_t *const sprite_{name}_frames[{count}] = {{\n"]
        table += [f"    &{s},\n" for s in frames]
        table.append("};\n\n")
        table.append(f"const SpriteInfo sprite_{name} = {{\n"
                     f"    sprite_{name}_frames, {count}, {fps}, {fw}, {fh}, "
                     f"SPRITE_{loop_name.upper()},\n}};\n")
        outputs[GEN_REL / "sprites" / f"sprite_{name}.c"] = "".join(table).encode("utf-8")
        results.append(SpriteResult(name, frames, fw, fh, fps, SPRITE_LOOP_MODES[loop_name],
                                    f"{raw['file']}, {count} x {fw}x{fh} {cf_name}, {fps} fps, {loop_name}"))
    return results


