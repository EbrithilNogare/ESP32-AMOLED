#!/usr/bin/env python3
"""Build every UI asset listed in assets/assets.toml into src/ui/generated/.

    python tools/assets.py            regenerate (only changed files are written)
    python tools/assets.py --check    regenerate into a temp dir, compare with the
                                      committed output, exit 1 on any difference
    python tools/assets.py -v         also print per-asset details

Outputs (all committed, never hand-edited):
    src/ui/generated/assets.h         declares every font / image / sprite + ICON_* macros
    src/ui/generated/fonts/*.c        lv_font_conv output (LVGL C fonts)
    src/ui/generated/images/*.c       LVGLImage.py output (flash images)
    src/ui/generated/sprites/*.c      sprite frames (LVGLImage.py) + frame tables
    data/img/*.bin                    LVGLImage.py output for images with dest = "fs"

The output is deterministic: the same sources and tool versions give
byte-identical files, so CI can run --check.

Requirements: Python 3.11+, `pip install -r tools/requirements.txt`,
Node >= 18 and `npm ci --prefix tools` (lv_font_conv). See tools/README.md.
"""

