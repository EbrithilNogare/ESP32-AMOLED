def utf8_c_literal(cp: int) -> str:
    return '"' + "".join(f"\\x{b:02X}" for b in chr(cp).encode("utf-8")) + '"'


def build_header(fonts: list[FontResult], images: list[tuple[str, str]],
                 sprites: list[SpriteResult]) -> str:
    out = [BANNER, "#pragma once\n\n", "#include <stdint.h>\n", '#include "lvgl.h"\n\n',
           "#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n"]

    out.append("/* Sprite sheet sliced into frames (see docs/UI_DESIGN.md §7, Sprites). */\n"
               "typedef struct SpriteInfo {\n"
               "    const lv_image_dsc_t *const *frames;\n"
               "    uint16_t count;\n"
               "    uint16_t fps;\n"
               "    uint16_t w, h;\n"
               "    uint8_t loop;   /* SPRITE_LOOP | SPRITE_ONCE | SPRITE_PINGPONG */\n"
               "} SpriteInfo;\n\n"
               "#define SPRITE_LOOP     0\n"
               "#define SPRITE_ONCE     1\n"
               "#define SPRITE_PINGPONG 2\n\n")

    out.append("/* ---- Fonts ---- */\n")
    width = max((len(f.spec.symbol) for f in fonts), default=0)
    for f in fonts:
        out.append(f"LV_FONT_DECLARE({f.spec.symbol}){' ' * (width - len(f.spec.symbol))}"
                   f"  /* {c_comment_safe(f.desc)} */\n")
    out.append("\n/* ---- Images ---- */\n")
    if not images:
        out.append("/* (none) */\n")
    # Plain externs, not LV_IMAGE_DECLARE: that macro comes with the image
    # widget (LV_USE_IMAGE), which the firmware leaves out; lv_draw_image()
    # draws these without it.
    for sym, desc in images:
        out.append(f"extern const lv_image_dsc_t {sym};  /* {c_comment_safe(desc)} */\n")
    out.append("\n/* ---- Sprites ---- */\n")
    if not sprites:
        out.append("/* (none) */\n")
    for s in sprites:
        out.append(f"/* {c_comment_safe(s.desc)} */\n")
        for fr in s.frames:
            out.append(f"extern const lv_image_dsc_t {fr};\n")
        out.append(f"extern const lv_image_dsc_t *const sprite_{s.name}_frames[{len(s.frames)}];\n")
        out.append(f"extern const SpriteInfo sprite_{s.name};\n\n")

    # Icons: union over all icon fonts, in manifest order.
    icons: dict[str, int] = {}
    in_fonts: dict[str, list[str]] = {}
    icon_fonts = [f for f in fonts if f.icons]
    for f in icon_fonts:
        for n, cp in f.icons.items():
            icons.setdefault(n, cp)
            in_fonts.setdefault(n, []).append(f.spec.symbol)
    out.append("\n/* ---- Icons: UTF-8 strings for the icon fonts ---- */\n")
    if icon_fonts:
        out.append("/* Glyphs in: " + ", ".join(f.spec.symbol for f in icon_fonts)
                   + " (unless noted). Codepoints from the official .codepoints file. */\n")
    width = max((len(n) for n in icons), default=0)
    for n, cp in icons.items():
        note = ""
        if len(in_fonts[n]) != len(icon_fonts):
            note = " only in " + ", ".join(in_fonts[n])
        out.append(f"#define ICON_{n.upper()}{' ' * (width - len(n))} {utf8_c_literal(cp)}"
                   f"  /* U+{cp:04X}{note} */\n")

    out.append("\n#ifdef __cplusplus\n} /* extern \"C\" */\n#endif\n")
    return "".join(out)


