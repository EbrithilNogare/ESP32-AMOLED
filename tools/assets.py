def generate(work: Path, verbose: bool, jobs: int) -> tuple[dict[Path, bytes], list[FontResult]]:
    ctx = load_manifest(MANIFEST)
    outputs: dict[Path, bytes] = {}

    fonts: list[FontResult] = []
    if ctx["fonts"]:
        check_lv_font_conv()
        # Download each remote source once before fanning out.
        for spec in ctx["fonts"]:
            if spec.source:
                src = ctx["sources"][spec.source]
                fetch(src["url"], src["sha256"])
                if "codepoints" in src:
                    fetch(src["codepoints"], src["codepoints_sha256"])
        fwork = work / "fonts"
        fwork.mkdir(parents=True)

        def one(spec: FontSpec) -> FontResult:
            d = fwork / spec.name
            d.mkdir()
            return build_font(spec, ctx, d, verbose)

        with ThreadPoolExecutor(max_workers=max(1, jobs)) as ex:
            fonts = list(ex.map(one, ctx["fonts"]))
        for r in fonts:
            log(f"  font   {r.spec.symbol:<20} {glyph_bitmap_bytes(r.text):>8} B glyph bitmaps"
                + (f"  ({r.notes})" if r.notes and verbose else ""))
            outputs[r.rel_out] = r.text.encode("utf-8")

    iwork = work / "images"
    iwork.mkdir()
    images = build_images(ctx["images"], iwork, outputs)
    swork = work / "sprites"
    swork.mkdir()
    sprites = build_sprites(ctx["sprites"], swork, outputs)
    for s in sprites:
        log(f"  sprite sprite_{s.name} ({len(s.frames)} frames)")

    outputs[GEN_REL / "assets.h"] = build_header(fonts, images, sprites).encode("utf-8")
    return outputs, fonts


def existing_outputs() -> dict[Path, Path]:
    found: dict[Path, Path] = {}
    gen = ROOT / GEN_REL
    if gen.is_dir():
        for p in sorted(gen.rglob("*")):
            if p.is_file():
                found[p.relative_to(ROOT)] = p
    fs = ROOT / FS_REL
    if fs.is_dir():
        for p in sorted(fs.glob("*.bin")):
            found[p.relative_to(ROOT)] = p
    return found


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="don't write; exit 1 if the committed output differs from a fresh build")
    ap.add_argument("-v", "--verbose", action="store_true")
    ap.add_argument("-j", "--jobs", type=int, default=os.cpu_count() or 1,
                    help="parallel font conversions (default: CPU count)")
    args = ap.parse_args()

    with tempfile.TemporaryDirectory(prefix="assets-") as tmp:
        try:
            outputs, fonts = generate(Path(tmp), args.verbose, args.jobs)
        except AssetError as e:
            print(f"error: {e}", file=sys.stderr)
            return 2
        except KeyError as e:
            print(f"error: assets.toml entry is missing required key {e}", file=sys.stderr)
            return 2

    total = sum(glyph_bitmap_bytes(r.text) for r in fonts)
    log(f"  fonts: {len(fonts)}, glyph bitmaps {total} B total")

    current = existing_outputs()

    def same(path: Path, data: bytes) -> bool:
        have = path.read_bytes()
        if path.suffix in (".c", ".h"):   # tolerate a CRLF checkout (core.autocrlf)
            have = have.replace(b"\r\n", b"\n")
        return have == data

    changed = [p for p, data in sorted(outputs.items())
               if p not in current or not same(current[p], data)]
    stale = [p for p in current if p not in outputs]

    if args.check:
        if changed or stale:
            print("error: generated assets are out of date — run `python tools/assets.py` "
                  "and commit the result:", file=sys.stderr)
            for p in changed:
                print(f"  {'changed' if p in current else 'missing'}: {p.as_posix()}", file=sys.stderr)
            for p in stale:
                print(f"  stale:   {p.as_posix()}", file=sys.stderr)
            return 1
        log("assets up to date")
        return 0

    for p in changed:
        dest = ROOT / p
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(outputs[p])
        log(f"  wrote   {p.as_posix()}")
    for p in stale:
        (ROOT / p).unlink()
        log(f"  removed {p.as_posix()}")
    # Drop directories left empty under the generated tree.
    gen = ROOT / GEN_REL
    if gen.is_dir():
        for d in sorted((d for d in gen.rglob("*") if d.is_dir()), reverse=True):
            if not any(d.iterdir()):
                d.rmdir()
    log("done" if (changed or stale) else "assets already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
