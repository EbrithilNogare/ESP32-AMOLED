@dataclass
class FontSpec:
    name: str
    size: int
    bpp: int
    file: str | None = None
    source: str | None = None
    ranges: list[str] = field(default_factory=list)
    symbols: str = ""
    icons: list[str] = field(default_factory=list)
    variations: dict[str, float] = field(default_factory=dict)
    kerning: str = "fast"            # fast | pairs | none
    compress: bool = False

    @property
    def symbol(self) -> str:
        return f"font_{self.name}"


def parse_cp_range(text: str) -> list[int]:
    """'0x20-0x7E', '0x2013' or '32-126' -> list of codepoints."""
    num = r"(0x[0-9a-fA-F]+|\d+)"
    mo = re.fullmatch(num + r"(?:-" + num + r")?", text.strip())
    if not mo:
        raise AssetError(f"bad range {text!r} (use '0x20-0x7E' or '0x2013')")
    lo = int(mo.group(1), 0)
    hi = int(mo.group(2), 0) if mo.group(2) else lo
    if hi < lo:
        raise AssetError(f"bad range {text!r}")
    return list(range(lo, hi + 1))


def ident(name: str, what: str) -> str:
    if not re.fullmatch(r"[a-z][a-z0-9_]*", name):
        raise AssetError(f"{what} name {name!r} must match [a-z][a-z0-9_]*")
    return name


def load_manifest(path: Path) -> dict:
    with path.open("rb") as f:
        m = tomllib.load(f)
    known = {"source", "font", "image", "sprite"}
    unknown = set(m) - known
    if unknown:
        raise AssetError(f"unknown top-level keys in {path.name}: {sorted(unknown)}")

    fonts: list[FontSpec] = []
    for raw in m.get("font", []):
        raw = dict(raw)
        allowed = {"name", "file", "source", "size", "bpp", "range", "symbols", "icons",
                   "variations", "kerning", "compress"}
        bad = set(raw) - allowed
        if bad:
            raise AssetError(f"font {raw.get('name')!r}: unknown keys {sorted(bad)}")
        spec = FontSpec(
            name=ident(raw["name"], "font"),
            size=int(raw["size"]),
            bpp=int(raw.get("bpp", 4)),
            file=raw.get("file"),
            source=raw.get("source"),
            ranges=[str(r) for r in raw.get("range", [])],
            symbols=raw.get("symbols", ""),
            icons=list(raw.get("icons", [])),
            variations={k: float(v) for k, v in raw.get("variations", {}).items()},
            kerning=raw.get("kerning", "none" if raw.get("icons") else "fast"),
            compress=bool(raw.get("compress", False)),
        )
        if (spec.file is None) == (spec.source is None):
            raise AssetError(f"font {spec.name}: give exactly one of `file` or `source`")
        if spec.bpp not in (1, 2, 3, 4, 8):
            raise AssetError(f"font {spec.name}: bpp must be 1, 2, 3, 4 or 8")
        if spec.kerning not in ("fast", "pairs", "none"):
            raise AssetError(f"font {spec.name}: kerning must be fast | pairs | none")
        if spec.source and spec.source not in m.get("source", {}):
            raise AssetError(f"font {spec.name}: unknown source {spec.source!r}")
        if spec.icons and not spec.source:
            raise AssetError(f"font {spec.name}: `icons` needs a `source` with a codepoints file")
        if not (spec.ranges or spec.symbols or spec.icons):
            raise AssetError(f"font {spec.name}: no glyphs (range/symbols/icons)")
        fonts.append(spec)

    names = [f.name for f in fonts]
    for kind, allowed in (("image", IMAGE_KEYS), ("sprite", SPRITE_KEYS)):
        for raw in m.get(kind, []):
            bad = set(raw) - allowed
            if bad:
                raise AssetError(f"{kind} {raw.get('name')!r}: unknown keys {sorted(bad)}")
            ident(raw["name"], kind)
            names.append(f"{kind}:{raw['name']}")
    dup = {n for n in names if names.count(n) > 1}
    if dup:
        raise AssetError(f"duplicate asset names: {sorted(dup)}")

    return {"sources": m.get("source", {}), "fonts": fonts,
            "images": m.get("image", []), "sprites": m.get("sprite", [])}


# ---------------------------------------------------------------------------
# Remote sources (pinned URL + SHA-256, cached in tools/.cache/)
# ---------------------------------------------------------------------------

def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _ssl_context() -> ssl.SSLContext:
    cafile = None
    if not os.environ.get("SSL_CERT_FILE"):
        cafile = os.environ.get("REQUESTS_CA_BUNDLE") or None
    return ssl.create_default_context(cafile=cafile)


def fetch(url: str, sha256: str) -> Path:
    """Download `url` once into tools/.cache/ and verify its SHA-256."""
    sha256 = sha256.lower()
    base = urllib.parse.unquote(url.rsplit("/", 1)[-1])
    base = re.sub(r"[^A-Za-z0-9._-]", "_", base)
    dest = CACHE / "downloads" / f"{sha256[:16]}-{base}"
    if dest.exists() and sha256_file(dest) == sha256:
        return dest
    dest.parent.mkdir(parents=True, exist_ok=True)
    log(f"  downloading {url}")
    tmp = dest.with_suffix(dest.suffix + ".part")
    req = urllib.request.Request(url, headers={"User-Agent": "esp32-amoled-assets"})
    with urllib.request.urlopen(req, context=_ssl_context(), timeout=120) as r, tmp.open("wb") as f:
        shutil.copyfileobj(r, f)
    got = sha256_file(tmp)
    if got != sha256:
        tmp.unlink()
        raise AssetError(f"SHA-256 mismatch for {url}\n  expected {sha256}\n  got      {got}")
    tmp.replace(dest)
    return dest


def load_codepoints(path: Path) -> dict[str, int]:
    cps: dict[str, int] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        parts = line.split()
        if len(parts) == 2:
            cps.setdefault(parts[0], int(parts[1], 16))
    return cps


