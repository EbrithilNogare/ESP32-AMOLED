# Variable font -> static subset (fontTools)
# ---------------------------------------------------------------------------

def make_static_subset(src: Path, codepoints: list[int], variations: dict[str, float],
                       out: Path) -> tuple[dict[int, str], int]:
    """Subset `src` to `codepoints`, pin every variation axis, bake default
    single substitutions into the cmap, and save a small static TTF.

    Returns ({codepoint: final glyph name}, number of substituted glyphs)."""
    from fontTools import subset
    from fontTools.ttLib import TTFont
    from fontTools.varLib import instancer

    font = TTFont(str(src))
    if "fvar" in font:
        axes = {a.axisTag: a for a in font["fvar"].axes}
        missing = set(axes) - set(variations)
        extra = set(variations) - set(axes)
        if missing or extra:
            raise AssetError(f"{src.name}: `variations` must pin exactly the axes "
                             f"{sorted(axes)} (missing {sorted(missing)}, unknown {sorted(extra)})")
        for tag, v in variations.items():
            a = axes[tag]
            if not a.minValue <= v <= a.maxValue:
                raise AssetError(f"{src.name}: {tag}={v} outside {a.minValue}..{a.maxValue}")
    elif variations:
        raise AssetError(f"{src.name} is not a variable font but `variations` was given")

    # 1. Subset first (fast instancing), keeping GSUB so the closure retains
    #    glyphs reachable through substitutions (e.g. "lightbulb.fill").
    opts = subset.Options()
    opts.layout_features = ["*"]
    opts.glyph_names = True
    opts.notdef_outline = True
    opts.name_IDs = ["*"]
    opts.name_languages = ["*"]
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=codepoints)
    sub.subset(font)

    # 2. Pin all axes -> static font (feature variations are resolved too).
    if "fvar" in font:
        font = instancer.instantiateVariableFont(font, variations, inplace=False,
                                                 updateFontNames=False)

    # 3. Apply default-feature single substitutions to the cmap.
    cmap = font.getBestCmap()
    final = {cp: cmap[cp] for cp in codepoints if cp in cmap}
    base = dict(final)
    if "GSUB" in font:
        gsub = font["GSUB"].table
        idx: set[int] = set()
        if gsub.FeatureList:
            for fr in gsub.FeatureList.FeatureRecord:
                if fr.FeatureTag in DEFAULT_SHAPING_FEATURES:
                    idx.update(fr.Feature.LookupListIndex)
        mappings = []
        for i in sorted(idx):
            lookup = gsub.LookupList.Lookup[i]
            for st in lookup.SubTable:
                if lookup.LookupType == 7:
                    if st.ExtensionLookupType != 1:
                        continue
                    st = st.ExtSubTable
                elif lookup.LookupType != 1:
                    continue
                mappings.append(st.mapping)
        for cp, g in final.items():
            for mp in mappings:
                g = mp.get(g, g)
            final[cp] = g
        for table in font["cmap"].tables:
            if table.isUnicode():
                for cp, g in final.items():
                    if cp in table.cmap:
                        table.cmap[cp] = g

    # 4. Subset again without layout tables: only the final glyphs remain.
    opts = subset.Options()
    opts.layout_features = []
    opts.drop_tables += ["GSUB", "GPOS", "GDEF", "STAT"]
    opts.glyph_names = False
    opts.notdef_outline = True
    opts.name_IDs = ["*"]
    opts.name_languages = ["*"]
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=codepoints)
    sub.subset(font)
    out.parent.mkdir(parents=True, exist_ok=True)
    font.save(str(out))
    return final, sum(1 for cp in final if final[cp] != base[cp])


