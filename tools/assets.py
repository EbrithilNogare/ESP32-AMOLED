def check_lv_font_conv() -> None:
    pkg = LV_FONT_CONV_JS.parent / "package.json"
    if not pkg.exists():
        raise AssetError("lv_font_conv is not installed: run `npm ci --prefix tools`")
    ver = json.loads(pkg.read_text())["version"]
    if ver != LV_FONT_CONV_VERSION:
        raise AssetError(f"lv_font_conv {ver} installed, {LV_FONT_CONV_VERSION} required: "
                         "run `npm ci --prefix tools`")
    if shutil.which("node") is None:
        raise AssetError("node (>= 18) not found on PATH")


def round_half_up(x: float) -> int:
    return int(math.floor(x + 0.5))   # matches JS Math.round used by lv_font_conv


def font_metrics(path: Path, size: int) -> tuple[int, int]:
    from fontTools.ttLib import TTFont
    f = TTFont(str(path), lazy=True)
    scale = size / f["head"].unitsPerEm
    os2 = f["OS/2"]
    return (round_half_up(getattr(os2, "sCapHeight", 0) * scale),
            round_half_up(getattr(os2, "sxHeight", 0) * scale))


def font_cmap(path: Path) -> set[int]:
    from fontTools.ttLib import TTFont
    return set(TTFont(str(path), lazy=True).getBestCmap())


def c_comment_safe(text: str) -> str:
    return text.replace("*/", "*\\/")


def postprocess_font(text: str, spec: FontSpec, opts_line: str,
                     cap_height: int, x_height: int) -> str:
    text = text.replace("\r\n", "\n")
    text, n = re.subn(r"^ \* Opts: .*$", lambda _: " * Opts: " + c_comment_safe(opts_line),
                      text, count=1, flags=re.M)
    if n != 1:
        raise AssetError(f"{spec.symbol}: unexpected lv_font_conv output (Opts line)")

    # Fields LVGL >= 9.3 / 9.6 know but lv_font_conv 1.5.3 doesn't emit
    # (newer lv_font_conv, which generates LVGL's own built-in fonts, does):
    # cap/x height (LV_TEXT_LEADING_TRIM_*) and static_bitmap (draw units may
    # keep pointers into the const glyph bitmaps).
    text, n = re.subn(
        r"^(    \.base_line = -?\d+,[^\n]*\n)",
        lambda mo: (mo.group(1)
                    + "#if LV_VERSION_CHECK(9, 6, 0) || LVGL_VERSION_MAJOR >= 10\n"
                    + f"    .cap_height = {cap_height},          /*Cap height of the font*/\n"
                    + f"    .x_height = {x_height},            /*x-height of the font*/\n"
                    + "#endif\n"),
        text, count=1, flags=re.M)
    if n != 1:
        raise AssetError(f"{spec.symbol}: unexpected lv_font_conv output (base_line)")
    if not spec.compress:
        text, n = re.subn(
            r"^(    \.dsc = &font_dsc,)",
            lambda mo: ("#if LV_VERSION_CHECK(9, 3, 0) || LVGL_VERSION_MAJOR >= 10\n"
                        "    .static_bitmap = 1,    /*Bitmaps are stored as const so they are always static if not compressed */\n"
                        "#endif\n" + mo.group(1)),
            text, count=1, flags=re.M)
        if n != 1:
            raise AssetError(f"{spec.symbol}: unexpected lv_font_conv output (dsc)")

    text = BANNER + text.rstrip("\n") + "\n"
    return text


def glyph_bitmap_bytes(c_text: str) -> int:
    mo = re.search(r"glyph_bitmap\[\] = \{(.*?)\n\};", c_text, flags=re.S)
    if not mo:
        return 0
    body = re.sub(r"/\*.*?\*/", "", mo.group(1), flags=re.S)
    return len(re.findall(r"0x[0-9a-fA-F]+", body))


@dataclass
class FontResult:
    spec: FontSpec
    rel_out: Path
    text: str
    desc: str
    icons: dict[str, int]       # icon name -> codepoint (icon fonts only)
    notes: str = ""


def build_font(spec: FontSpec, ctx: dict, work: Path, verbose: bool) -> FontResult:
    cps: list[int] = []
    for r in spec.ranges:
        cps += parse_cp_range(r)
    cps += [ord(ch) for ch in spec.symbols]
    icons: dict[str, int] = {}
    notes = ""

    if spec.source:
        src = ctx["sources"][spec.source]
        src_font = fetch(src["url"], src["sha256"])
        if spec.icons:
            cp_file = fetch(src["codepoints"], src["codepoints_sha256"])
            table = load_codepoints(cp_file)
            missing = [n for n in spec.icons if n not in table]
            if missing:
                raise AssetError(f"font {spec.name}: unknown icon names {missing} "
                                 f"(see {src['codepoints']})")
            for n in spec.icons:
                icons[n] = table[n]
            cps += list(icons.values())
        cps = sorted(set(cps))
        static = work / f"{spec.name}.ttf"
        final, n_sub = make_static_subset(src_font, cps, spec.variations, static)
        lost = [f"U+{cp:04X}" for cp in cps if cp not in final]
        if lost:
            raise AssetError(f"font {spec.name}: codepoints missing in source: {lost}")
        notes = f"{len(cps)} glyphs, {n_sub} via default GSUB substitutions"
        font_path = static
        var_txt = ",".join(f"{k}={v:g}" for k, v in sorted(spec.variations.items()))
        src_name = urllib.parse.unquote(src["url"].rsplit("/", 1)[-1])
        display_font = f"{src_name}@{{{var_txt}}}"
        desc_font = f"{spec.source} {var_txt}"
    else:
        font_path = (ASSETS / spec.file).resolve()
        if not font_path.is_file():
            raise AssetError(f"font {spec.name}: {font_path} not found")
        cps = sorted(set(cps))
        have = font_cmap(font_path)
        lost = [f"U+{cp:04X}" for cp in cps if cp not in have]
        if lost and verbose:   # e.g. U+00AD soft hyphen: nothing to draw, lv_font_conv skips it
            log(f"  note: {spec.symbol}: {Path(spec.file).name} has no glyph for {', '.join(lost)}")
        display_font = f"assets/{spec.file}"
        desc_font = Path(spec.file).name

    rel_out = GEN_REL / "fonts" / f"{spec.symbol}.c"
    out_tmp = work / f"{spec.symbol}.c"

    glyph_args: list[str] = []
    ranges = [r.strip() for r in spec.ranges] + [f"0x{cp:X}" for cp in icons.values()]
    if ranges:
        glyph_args += ["-r", ",".join(ranges)]
    if spec.symbols:
        glyph_args += ["--symbols", spec.symbols]

    common = ["--size", str(spec.size), "--bpp", str(spec.bpp), "--format", "lvgl"]
    if not spec.compress:
        common += ["--no-compress", "--no-prefilter"]
    if spec.kerning == "fast":
        common += ["--force-fast-kern-format"]
    elif spec.kerning == "none":
        common += ["--no-kerning"]
    common += ["--lv-include", "lvgl.h", "--lv-font-name", spec.symbol]

    args = ["node", str(LV_FONT_CONV_JS), "--font", str(font_path), *glyph_args, *common,
            "-o", str(out_tmp)]
    shown = ["lv_font_conv", "--font", display_font, *glyph_args, *common,
             "-o", rel_out.as_posix()]
    proc = subprocess.run(args, cwd=work, capture_output=True, text=True)
    if proc.returncode != 0:
        raise AssetError(f"lv_font_conv failed for {spec.name}:\n{proc.stdout}{proc.stderr}")
    if verbose and proc.stdout.strip():
        log(f"  {spec.symbol}: {proc.stdout.strip()}")

    cap_h, x_h = font_metrics(font_path, spec.size)
    text = postprocess_font(out_tmp.read_text(encoding="utf-8"), spec, shlex.join(shown),
                            cap_h, x_h)
    glyph_txt = ", ".join(spec.ranges) if spec.ranges else ""
    if spec.symbols:
        glyph_txt = (glyph_txt + ", " if glyph_txt else "") + f'"{spec.symbols}"'
    if icons:
        glyph_txt = f"{len(icons)} icons"
    desc = f"{desc_font}, {spec.size} px, {spec.bpp} bpp, {glyph_txt}"
    return FontResult(spec, rel_out, text, desc, icons, notes)


